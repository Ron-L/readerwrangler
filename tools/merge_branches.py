#!/usr/bin/env python3
"""
merge_branches.py — merge task branches into a target branch (default main-prime), never hand-merging what is generated
or always differs (TODO "Faster sprints", item 4; Ron, 2026-11-15: "Can they all branch … and then you merge them
together?").

    py tools/merge_branches.py <branch> [<branch> …] [--into <target>] [--no-squash] [--no-test]
    py tools/merge_branches.py --continue     after resolving a real conflict by hand (or fixing a failed test run)
    py tools/merge_branches.py --abort        give up: back on the target, exactly as it was

Run it in a folder whose current branch is the target, with nothing uncommitted — a working copy (tools/copies.py) or
the main folder. The target moves only at the end, and only once the merged result has passed.

  1. A scratch branch, merging/<target>, is made at the target and the folder switched to it.
  2. Each branch, in the order given, is squash-merged onto it as ONE commit (as a sprint task goes into main-prime —
     CLAUDE.md; --no-squash: a real merge commit). What git can't merge by itself is settled here when it is generated
     or always differs — and redone after every branch even when git merged it cleanly:
       dist/                          rebuilt by tools/build.py from the merged sources — never merged
       docs/design/MESSAGE-CODES.md   regenerated by tools/message_codes.py
       TODO.md's table of contents    rebuilt from the merged headers — ONLY the table: the tasks are real content
       the version stamps             ORGANIZER_VERSION, MOBILE_VERSION's -alpha suffix and every ?v= cache-buster the
                                      branch moved: set to a fresh alpha above every merged branch's (below)
     Any other conflict stops the run: each conflicted file is named and the merge is left in place for a person —
     resolve, `git add`, then --continue. The commit checks (git-hooks/) run on every commit, as always.
  3. Tier 1 and tier 2 in full on the merged result — committed on the scratch branch, so the stamp proves exactly the
     commit that lands — and `run_tests.py --stamp` must say PROVEN. Then the target is fast-forwarded there, the folder
     switched back to it and the scratch branch deleted. A failure leaves the target untouched and the folder on the
     scratch branch (fix and commit there, then --continue; or --abort). --no-test lands without testing and says,
     loudly, that nothing was proven.

The fresh version: the highest ORGANIZER_VERSION among the target and every branch given (and their ?v= stamps), one
alpha up — for the first branch that moved a stamp; the next such branch gets the next alpha, and so on, so each commit
is its own build and the last one is above everything merged. A branch that moved any stamp moves ORGANIZER_VERSION
with it (the merged build gets its own number). MOBILE_VERSION keeps its own X.Y.Z (the higher of the two sides) with
the fresh -alpha.N.

Tested by test/test_merge_branches.py (real git, throwaway repositories).
"""
import argparse
import json
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GENERATED_DIR = "dist/"
CODES = "docs/design/MESSAGE-CODES.md"
TODO = "TODO.md"
CONSTS = {"readerwrangler.js": "ORGANIZER_VERSION", "mobile.js": "MOBILE_VERSION"}
REF = re.compile(r'((?:src|href)="([A-Za-z0-9_./-]+)\?v=)([^"]*)(")')
VERSION = re.compile(r"^(\d+)\.(\d+)\.(\d+)(?:-alpha\.(\d+))?$")
MASK = "@@RW-STAMP@@"
GIT_LOCATION_VARS = ("GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE", "GIT_OBJECT_DIRECTORY", "GIT_COMMON_DIR",
                     "GIT_ALTERNATE_OBJECT_DIRECTORIES", "GIT_PREFIX")


class Stop(Exception):
    """The run stops here, for a person: the message says what to do; exit code 1 (or 2 = a real conflict)."""

    def __init__(self, message, code=1):
        super().__init__(message)
        self.code = code


def _env():
    return {k: v for k, v in os.environ.items() if k not in GIT_LOCATION_VARS}


class Repo:
    def __init__(self, folder):
        self.dir = folder

    def git(self, *args, check=True, binary=False):
        r = subprocess.run(["git", *args], cwd=self.dir, env=_env(), capture_output=True)
        if check and r.returncode:
            raise Stop(f"git {' '.join(args)} failed:\n{(r.stderr or r.stdout).decode('utf-8', 'replace').strip()}")
        return r if binary else subprocess.CompletedProcess(r.args, r.returncode, r.stdout.decode("utf-8", "replace"),
                                                            r.stderr.decode("utf-8", "replace"))

    def out(self, *args):
        return self.git(*args).stdout.strip()

    def show(self, spec):
        """A file's text at a commit or index stage ('HEAD:x', ':2:x'), or None."""
        r = self.git("show", spec, check=False, binary=True)
        return r.stdout.decode("utf-8", "replace").replace("\r\n", "\n") if r.returncode == 0 else None

    def path(self, rel):
        return os.path.join(self.dir, rel)

    def read(self, rel):
        try:
            with open(self.path(rel), encoding="utf-8", newline="") as f:
                return f.read()
        except OSError:
            return None

    def write(self, rel, text):
        with open(self.path(rel), "w", encoding="utf-8", newline="") as f:
            f.write(text)

    def run_tool(self, script, *args):
        """One of the folder's own tools (tools/build.py …) with this Python, if the branch has it. (ok, its output)."""
        p = self.path(script)
        if not os.path.exists(p):
            return True, ""
        r = subprocess.run([sys.executable, p, *args], cwd=self.dir, env=_env(), capture_output=True, text=True,
                           encoding="utf-8", errors="replace")
        return r.returncode == 0, (r.stdout or "") + (r.stderr or "")

    def git_path(self, name):
        """A file in git's own folder for this working copy (MERGE_HEAD, SQUASH_MSG, the run's state)."""
        return os.path.normpath(os.path.join(self.dir, self.out("rev-parse", "--git-path", name)))

    def state_file(self):
        return self.git_path("rw-merge-state.json")


# --- versions --------------------------------------------------------------------------------------------------------
def parse_version(v):
    m = VERSION.match(v or "")
    if not m:
        return None
    x, y, z, a = m.groups()
    return int(x), int(y), int(z), (int(a) if a is not None else None)


def version_order(v):
    x, y, z, a = parse_version(v)
    return x, y, z, 0 if a is not None else 1, a or 0      # 7.31.0-alpha.9 < 7.31.0


def next_alpha(v):
    x, y, z, a = parse_version(v)
    return f"{x}.{y}.{z}-alpha.{a + 1}" if a is not None else f"{x}.{y}.{z + 1}-alpha.1"


# --- stamps: where they are, read and set by one pair of rules ---------------------------------------------------------
def stamp_files(names):
    return sorted(n for n in names if n in CONSTS or (n.endswith(".html") and "/" not in n))


def _const_re(name):
    return re.compile(r"(\b" + name + r"\s*=\s*[\"'])([^\"']*)([\"'])")


def read_stamps(rel, text):
    """{key: value} — ('const', NAME) for ORGANIZER_VERSION / MOBILE_VERSION, ('ref', page, file) for a ?v= stamp."""
    out = {}
    if text is None:
        return out
    if rel in CONSTS:
        m = _const_re(CONSTS[rel]).search(text)
        if m:
            out[("const", CONSTS[rel])] = m.group(2)
    elif rel.endswith(".html"):
        for m in REF.finditer(text):
            out[("ref", rel, m.group(2))] = m.group(3)
    return out


def set_stamps(rel, text, values, default=None):
    """The text with each stamp set to values[key] (missing: `default`, or left as it is when that's None)."""
    def pick(key, old):
        return values.get(key, old if default is None else default)
    if rel in CONSTS:
        name = CONSTS[rel]
        return _const_re(name).sub(lambda m: m.group(1) + pick(("const", name), m.group(2)) + m.group(3), text)
    return REF.sub(lambda m: m.group(1) + pick(("ref", rel, m.group(2)), m.group(3)) + m.group(4), text)


def stamps_at(repo, rev):
    names = repo.out("ls-tree", "-r", "--name-only", rev).splitlines()
    out = {}
    for rel in stamp_files(names):
        out.update(read_stamps(rel, repo.show(f"{rev}:{rel}")))
    return out


def highest_version(repo, revs):
    found = []
    for rev in revs:
        for key, v in stamps_at(repo, rev).items():
            if key != ("const", "MOBILE_VERSION") and parse_version(v):
                found.append(v)
    return max(found, key=version_order) if found else None


def decide_stamps(base, ours, theirs, fresh):
    """What every stamp becomes after merging `theirs` (a branch) onto `ours`: each stamp the branch moved (relative to
    the merge base) takes the fresh version — and ORGANIZER_VERSION with them; the rest keep ours."""
    moved = {k for k, v in theirs.items() if base.get(k) != v}
    decided = {k: ours.get(k, theirs.get(k)) for k in set(ours) | set(theirs)}
    if not moved or fresh is None:
        return decided, False
    alpha = parse_version(fresh)[3]
    for k in moved | ({("const", "ORGANIZER_VERSION")} & set(decided)):
        if k == ("const", "MOBILE_VERSION"):
            sides = [v for v in (ours.get(k), theirs.get(k)) if parse_version(v)]
            x, y, z, _ = max((parse_version(v) for v in sides), default=(1, 0, 0, None))
            decided[k] = f"{x}.{y}.{z}-alpha.{alpha}"
        else:
            decided[k] = fresh
    return decided, True


# --- TODO.md's table of contents (the same reading of headers as git-hooks/check-toc.js) ---------------------------------
TOC_START, TOC_END = "<!-- TOC -->", "<!-- /TOC -->"


def slug(text):
    """The link the VS Code extension "Auto Markdown TOC" gives a header (2026-11-16: this rule matches all 153 entries
    of the TODO's table): lower case, punctuation and emoji dropped, spaces to hyphens."""
    return re.sub(r"[^\w\- ]", "", text.lower()).replace(" ", "-").strip("-")


def rebuild_toc(text):
    """The text with its table of contents rebuilt from its headers; None when it has no table. Conflict markers are
    allowed INSIDE the table only (that's the generated part); anywhere else → ValueError."""
    if "\r\n" in text:
        new = rebuild_toc(text.replace("\r\n", "\n"))
        return None if new is None else new.replace("\n", "\r\n")
    lines = text.split("\n")
    starts = [i for i, ln in enumerate(lines) if ln.strip() == TOC_START]
    ends = [i for i, ln in enumerate(lines) if ln.strip() == TOC_END]
    if not starts or not ends:
        return None
    if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
        raise ValueError("its table-of-contents markers are repeated or out of order")
    start, end = starts[0], ends[0]
    inside = False
    for i, ln in enumerate(lines):
        if ln.startswith("<<<<<<< "):
            inside = True
        if inside and not start < i < end:
            raise ValueError(f"a conflict outside the table of contents (line {i + 1}) — the tasks are real content")
        if ln.startswith(">>>>>>> "):
            inside = False
    headers, fence = [], False
    for i, ln in enumerate(lines):
        if start <= i <= end:
            continue
        if re.match(r"^\s*```", ln):
            fence = not fence
            continue
        m = not fence and re.match(r"^(#{1,6})\s+(.*?)\s*#*\s*$", ln)
        if m:
            headers.append((len(m.group(1)), m.group(2)))
    top = min((lvl for lvl, _ in headers), default=1)
    seen, toc = {}, []
    for lvl, h in headers:
        s = slug(h)
        n = seen.get(s, 0)
        seen[s] = n + 1
        toc.append("  " * (lvl - top) + f"- [{h}](#{s if n == 0 else f'{s}-{n}'})")
    return "\n".join(lines[:start + 1] + [""] + toc + [""] + lines[end:])


# --- one branch ------------------------------------------------------------------------------------------------------
def unmerged(repo):
    return [p for p in repo.out("diff", "--name-only", "--diff-filter=U").splitlines() if p]


def take_ours(repo, rel):
    side = "--ours" if repo.git("cat-file", "-e", f":2:{rel}", check=False).returncode == 0 else "--theirs"
    repo.git("checkout", side, "--", rel)
    repo.git("add", "--", rel)


def merge_stamped(repo, rel, decided):
    """A conflicted file that carries stamps: merged again with every stamp hidden — so two branches that each moved a
    stamp don't collide on that line — then the decided stamps written in. False = a real conflict remains."""
    stages = [repo.show(f":{n}:{rel}") for n in (2, 1, 3)]          # ours, base, theirs
    if any(s is None for s in stages):
        return False
    with tempfile.TemporaryDirectory(prefix="rw-merge-") as tmp:
        paths = []
        for name, text in zip(("ours", "base", "theirs"), stages):
            paths.append(os.path.join(tmp, name))
            with open(paths[-1], "w", encoding="utf-8", newline="") as f:
                f.write(set_stamps(rel, text, {}, default=MASK))
        r = subprocess.run(["git", "merge-file", "-p", *paths], capture_output=True, env=_env())
    if r.returncode != 0:
        return False
    merged = set_stamps(rel, r.stdout.decode("utf-8", "replace"), decided)
    if MASK in merged:
        return False
    repo.write(rel, merged)
    repo.git("add", "--", rel)
    return True


def settle_conflicts(repo, decided):
    """Settle every conflict that is generated or a stamp; return the real ones (left as git wrote them)."""
    real = []
    for rel in unmerged(repo):
        if rel.startswith(GENERATED_DIR) or rel == CODES:
            take_ours(repo, rel)                        # rebuilt / regenerated in finish_step
        elif rel == TODO:
            try:
                text = rebuild_toc(repo.read(rel) or "")
            except ValueError:
                text = None
            if text is None:
                real.append(rel)
            else:
                repo.write(rel, text)
                repo.git("add", "--", rel)
        elif rel in stamp_files([rel]):
            if not merge_stamped(repo, rel, decided):
                real.append(rel)
        else:
            real.append(rel)
    return real


def finish_step(repo, step):
    """Stamps, then the generated files, then the commit (the commit checks run as for any commit)."""
    decided = {tuple(k): v for k, v in step["decided"]}
    tracked = repo.out("ls-files").splitlines()
    for rel in stamp_files(tracked):
        text = repo.read(rel)
        if text is not None:
            new = set_stamps(rel, text, decided)
            if new != text:
                repo.write(rel, new)
                repo.git("add", "--", rel)
    for script, args, what in (("tools/build.py", (), "dist/ (tools/build.py)"),
                               ("tools/message_codes.py", (), f"{CODES} (tools/message_codes.py)")):
        ok, out = repo.run_tool(script, *args)
        if not ok:
            raise Stop(f"couldn't regenerate {what}:\n{out.strip()}\nFix it on this branch, `git add`, then --continue.")
    text = repo.read(TODO)
    if text is not None:
        try:
            new = rebuild_toc(text)
        except ValueError as e:
            raise Stop(f"{TODO}: {e}")
        if new is not None and new != text:
            repo.write(TODO, new)
    status = repo.git("status", "--porcelain", "-z", "--untracked-files=all", "--", GENERATED_DIR, CODES, TODO).stdout
    for entry in (e for e in status.split("\0") if len(e) > 3):
        repo.git("add", "--", entry[3:])               # "XY path" — what the regenerating changed or made
    if not repo.out("diff", "--cached", "--name-only") and not os.path.exists(repo.git_path("MERGE_HEAD")):
        squash_msg = repo.git_path("SQUASH_MSG")       # left by a squash, it would make the NEXT commit look like one
        if os.path.exists(squash_msg):                 # to the removed-tasks check (git-hooks/check-removed-tasks.py)
            os.remove(squash_msg)
        print(f"· {step['branch']}: nothing to merge — already in")
        return
    r = repo.git("commit", "-q", "-m", step["message"], check=False)
    if r.returncode:
        raise Stop(f"the commit of {step['branch']} was refused (the commit checks, above):\n{(r.stdout + r.stderr).strip()}"
                   "\nFix it on this branch, `git add`, then --continue.")
    print(f"· {step['branch']}: committed {repo.out('log', '-1', '--format=%h %s')[:110]}")


def start_step(repo, state, branch):
    """Merge one branch (no commit yet) and settle what's generated. Returns the step, or raises Stop on a real conflict."""
    base = repo.out("merge-base", "HEAD", branch)
    ours, theirs, at_base = stamps_at(repo, "HEAD"), stamps_at(repo, branch), stamps_at(repo, base)
    fresh = next_alpha(state["version"]) if state["version"] else None
    decided, used = decide_stamps(at_base, ours, theirs, fresh)
    if used:
        state["version"] = fresh
    topic = re.sub(r"^\d+\.\d+\.\d+(-alpha\.\d+)?:\s*", "", repo.out("log", "-1", "--format=%s", branch))
    commits = repo.out("log", "--reverse", "--format=- %s", f"{base}..{branch}").splitlines()
    head = f"{fresh}: " if used else ""
    if state["squash"]:
        title = f"{head}{topic} (squashed from {branch} by tools/merge_branches.py)"
    else:
        title = f"{head}Merge branch '{branch}' into {state['target']} (tools/merge_branches.py)"
    body = ("Regenerated, not merged: dist/, MESSAGE-CODES.md, TODO's table of contents"
            + (f"; version stamps the branch moved set to {fresh}" if used else "") + ".\n\nThe branch's commits:\n"
            + "\n".join(commits[:30]) + (f"\n- … and {len(commits) - 30} more" if len(commits) > 30 else ""))
    step = {"branch": branch, "fresh": fresh if used else None, "squash": state["squash"],
            "decided": [[list(k), v] for k, v in decided.items()], "message": f"{title}\n\n{body}"}
    state["step"] = step
    save_state(repo, state)
    args = ["merge", "--squash", branch] if state["squash"] else ["merge", "--no-ff", "--no-commit", branch]
    r = repo.git(*args, check=False)
    if r.returncode and not unmerged(repo):
        raise Stop(f"git couldn't merge {branch}:\n{(r.stdout + r.stderr).strip()}")
    real = settle_conflicts(repo, decided)
    if real:
        raise Stop(f"STOPPED — {branch} conflicts with what's already merged, in:\n  " + "\n  ".join(real)
                   + "\nThe merge is left in place (folder on " + state["scratch"] + "). Resolve each file (both sides "
                   "are in it), `git add` it, then:  py tools/merge_branches.py --continue   (or --abort)", code=2)
    return step


# --- the run ---------------------------------------------------------------------------------------------------------
def save_state(repo, state):
    with open(repo.state_file(), "w", encoding="utf-8") as f:
        json.dump(state, f, indent=1)


def load_state(repo):
    try:
        with open(repo.state_file(), encoding="utf-8") as f:
            return json.load(f)
    except OSError:
        return None


def clear_state(repo):
    try:
        os.remove(repo.state_file())
    except OSError:
        pass


def proven(repo):
    r = subprocess.run([sys.executable, repo.path("tools/run_tests.py"), "--stamp"], cwd=repo.dir, env=_env(),
                       capture_output=True, text=True, encoding="utf-8", errors="replace")
    return r.returncode == 0, r.stdout.strip()


def test_and_land(repo, state):
    if state["test"]:
        for tier in ("1", "2"):
            print(f"· tier {tier} in full on the merged result (py tools/run_tests.py --tier {tier}) …", flush=True)
            code = subprocess.run([sys.executable, repo.path("tools/run_tests.py"), "--tier", tier], cwd=repo.dir,
                                  env=_env()).returncode
            if code:
                print(f"· tier {tier} failed — tier 2 not run" if tier == "1" else f"· tier {tier} failed")
                break
        ok, stamp = proven(repo)
        print(stamp)
        if not ok:
            raise Stop(f"NOT LANDED — the merged result isn't proven (above). {state['target']} is untouched; the folder "
                       f"is on {state['scratch']}. Fix and commit there, then --continue (it tests again) — or --abort.")
    repo.git("switch", "-q", state["target"])
    r = repo.git("merge", "-q", "--ff-only", state["scratch"], check=False)
    if r.returncode:
        raise Stop(f"{state['target']} moved while merging — not landed:\n{(r.stdout + r.stderr).strip()}\n"
                   f"The merged commits are on {state['scratch']}.")
    repo.git("branch", "-q", "-d", state["scratch"])
    clear_state(repo)
    print(f"LANDED — {state['target']} is now {repo.out('log', '-1', '--format=%h %s')[:110]}"
          + (f"\n  version {state['version']}" if state["version"] != state["version_before"] else ""))
    if not state["test"]:
        print("!! --no-test: NOTHING WAS PROVEN. The merged result was not tested — run tier 1 and tier 2 before "
              "anything else builds on it:  py tools/run_tests.py --tier 1  then  --tier 2")
    return 0


def run_steps(repo, state):
    while state["next"] < len(state["branches"]):
        if state.get("step") is None:
            start_step(repo, state, state["branches"][state["next"]])
        finish_step(repo, state["step"])
        state["step"] = None
        state["next"] += 1
        save_state(repo, state)
    return test_and_land(repo, state)


def begin(repo, a):
    target = a.into
    if load_state(repo):
        raise Stop("a merge is already under way here — finish it (--continue) or give it up (--abort)")
    here = repo.out("rev-parse", "--abbrev-ref", "HEAD")
    if here != target:
        raise Stop(f"this folder is on {here}, not {target}. Switch first (git switch {target}) — or merge into "
                   f"another branch with --into.")
    dirty = repo.out("status", "--porcelain", "--untracked-files=normal")
    if dirty:
        raise Stop("not merging over uncommitted changes:\n  " + "\n  ".join(dirty.splitlines()[:10]))
    for b in a.branches:
        if repo.git("rev-parse", "--verify", "--quiet", f"{b}^{{commit}}", check=False).returncode:
            raise Stop(f"{b!r} isn't a branch or commit here")
    scratch = f"merging/{target}"
    if repo.git("rev-parse", "--verify", "--quiet", f"refs/heads/{scratch}", check=False).returncode == 0:
        raise Stop(f"{scratch} already exists (a run that didn't finish?) — look at it, then delete it: "
                   f"git branch -D {scratch}")
    version = highest_version(repo, ["HEAD", *a.branches])
    state = {"target": target, "start": repo.out("rev-parse", "HEAD"), "scratch": scratch, "branches": a.branches,
             "next": 0, "squash": not a.no_squash, "test": not a.no_test, "version": version, "version_before": version,
             "step": None}
    repo.git("switch", "-q", "-c", scratch)
    save_state(repo, state)
    print(f"· merging {', '.join(a.branches)} into {target} on {scratch}"
          + (f" — the highest version among them: {version}" if version else ""))
    return run_steps(repo, state)


def resume(repo):
    state = load_state(repo)
    if not state:
        raise Stop("no merge is under way here")
    left = unmerged(repo)
    if left:
        raise Stop("still unresolved:\n  " + "\n  ".join(left) + "\nResolve each, `git add` it, then --continue.")
    return run_steps(repo, state)


def abort(repo):
    state = load_state(repo)
    if not state:
        raise Stop("no merge is under way here")
    repo.git("reset", "-q", "--merge")                  # the merge in progress (if any) undone — nothing else touched
    squash_msg = repo.git_path("SQUASH_MSG")            # (it would make the next commit look like a squash to the
    if os.path.exists(squash_msg):                      # removed-tasks check)
        os.remove(squash_msg)
    repo.git("switch", "-q", state["target"])
    if repo.out("rev-parse", "HEAD") != state["start"]:
        raise Stop(f"{state['target']} isn't where it was ({state['start'][:12]}) — left as it is; look before deleting "
                   f"{state['scratch']}")
    repo.git("branch", "-q", "-D", state["scratch"])
    clear_state(repo)
    print(f"ABORTED — back on {state['target']} at {state['start'][:12]}, exactly as before; {state['scratch']} deleted.")
    return 0


def main(argv=None, folder=ROOT):
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except Exception:
            pass
    ap = argparse.ArgumentParser(description="Merge task branches into a target branch, regenerating what's generated "
                                             "(docs/design/SESSION-TOOLING.md).")
    ap.add_argument("branches", nargs="*")
    ap.add_argument("--into", default="main-prime", help="the target branch (default main-prime) — the folder's branch")
    ap.add_argument("--no-squash", action="store_true", help="a real merge commit per branch instead of a squash")
    ap.add_argument("--no-test", action="store_true", help="land without testing (says loudly that nothing was proven)")
    ap.add_argument("--continue", dest="resume", action="store_true", help="carry on after resolving a conflict")
    ap.add_argument("--abort", action="store_true", help="give up: back on the target as it was")
    a = ap.parse_args(argv)
    repo = Repo(folder)
    try:
        if a.abort:
            return abort(repo)
        if a.resume:
            return resume(repo)
        if not a.branches:
            ap.print_help()
            return 1
        return begin(repo, a)
    except Stop as e:
        print(str(e), file=sys.stderr)
        return e.code


